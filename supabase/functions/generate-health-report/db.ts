/** Rate limit: counts health_reports rows generated by the caller within the last `windowHours`. */
export async function countRecentReports(
  supabase: SupabaseClient,
  userId: string,
  windowHours: number,
): Promise<number> {
  const windowStartISO = new Date(Date.now() - windowHours * 60 * 60 * 1000).toISOString();

  const { count, error } = await supabase
    .from("health_reports")
    .select("id", { count: "exact", head: true })
    .eq("user_id", userId)
    .gte("generated_at", windowStartISO);

  if (error) throw new Error(`countRecentReports failed: ${error.message}`);
  return count ?? 0;
}

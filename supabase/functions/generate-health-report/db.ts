// Data-fetching + row-mapping for the health report generator.
// Mirrors the shapes lib/trackingService.ts maps for the client, but only
// the fields insightsEngine.ts actually needs (no photo/full-nutrition mapping).
import type { SupabaseClient } from "@supabase/server/peer/supabase-js";
import type { BowelEntry, FoodEntry, WaterEntry } from "../../../types/tracking.ts";

type EntryRange = { startISO: string; endISO: string };

export async function fetchFoodEntries(
  supabase: SupabaseClient,
  range: EntryRange,
): Promise<Pick<FoodEntry, "id" | "timestamp" | "totalCalories" | "totalProtein" | "totalCarbs" | "totalFat" | "ingredients">[]> {
  const { data, error } = await supabase
    .from("food_entries")
    .select("id, timestamp, total_calories, total_protein, total_carbs, total_fat, food_ingredients(name)")
    .gte("timestamp", range.startISO)
    .lte("timestamp", range.endISO)
    .order("timestamp", { ascending: true });

  if (error) throw new Error(`fetchFoodEntries failed: ${error.message}`);

  return (data ?? []).map((row: any) => ({
    id: row.id,
    timestamp: row.timestamp,
    totalCalories: row.total_calories ?? undefined,
    totalProtein: row.total_protein ?? undefined,
    totalCarbs: row.total_carbs ?? undefined,
    totalFat: row.total_fat ?? undefined,
    ingredients: (row.food_ingredients ?? []).map((ing: any) => ({
      id: "",
      name: ing.name,
      amount: 0,
      unit: "g" as const,
    })),
  }));
}

